def limpiar_precio(texto):
    if not texto:
        return None
    limpio = texto.strip().replace(",", "")
    try:
        return float(limpio)
    except ValueError:
        return None


def limpiar_sku(texto):
    if not texto:
        return ""
    return texto.replace("Sku:", "").strip()


def construir_url_pagina(url_base, pagina):
    separador = "&" if "?" in url_base else "?"
    return url_base if pagina == 1 else f"{url_base}{separador}page={pagina}"


def procesar_datos(data):
    # Fecha de esta consulta, según la hora de El Salvador (UTC-6).
    # Se asigna al recibir los productos, no al exportar los archivos.
    fecha_consulta = datetime.now(timezone(timedelta(hours=-6))).strftime("%d-%m-%Y")
    for item in data:
        item["sku"] = limpiar_sku(item.get("sku", ""))
        item["precio"] = limpiar_precio(item.get("precio", ""))
        item["fecha_consulta"] = fecha_consulta
        item["proveedor"] = PROVEEDOR
    return data


